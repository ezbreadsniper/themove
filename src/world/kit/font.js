export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** Width in pixels of `text` at integer `scale` with 1-pixel letter spacing. */
export function textWidth(text, scale = 1) {
  return text.length * (GLYPH_W + 1) * scale - scale;
}

/**
 * Draws `text` into a Raster with its baseline-left corner at (x, y) (raster y grows up).
 * `wear` (0..1) drops random pixels so stencils and old paint look chipped.
 */
export function drawText(raster, text, x, y, color, { scale = 1, wear = 0, rng = null, alpha = 1 } = {}) {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const bits = GLYPHS[ch] ?? GLYPHS[' '];
    for (let row = 0; row < GLYPH_H; row++) {
      for (let col = 0; col < GLYPH_W; col++) {
        if (bits[row * GLYPH_W + col] !== '1') continue;
        if (wear > 0 && rng && rng.next() < wear) continue;
        raster.rect(cx + col * scale, y + (GLYPH_H - 1 - row) * scale, scale, scale, color, alpha);
      }
    }
    cx += (GLYPH_W + 1) * scale;
  }
  return cx - x;
}

/** Draws text centred horizontally on `cx`. */
export function drawTextCentered(raster, text, cx, y, color, opts = {}) {
  const w = textWidth(text, opts.scale ?? 1);
  return drawText(raster, text, Math.round(cx - w / 2), y, color, opts);
}
